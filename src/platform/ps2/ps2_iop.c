/*
 * Clean IOP reset + base module reload (see ps2_iop.h).
 *
 * Reset policy:
 *   - host: present (PCSX2, ps2link)          -> keep the loader I/O
 *   - FALLOUT/NO_IOP_RESET marker on mass/mc  -> keep the loader I/O
 *   - anything else                          -> SifIopReset + full reload
 *
 * After SifIopSync() the embedded ioman/iomanX/fileio modules are executed
 * first, because every later probe (mass:, mc0:, rom0: files) goes through
 * the FILEIO RPC service. SIO2MAN is loaded before MCMAN/MCSERV, and the pad
 * driver is loaded again by ps2_input_init() after this function returns.
 */

#include "ps2_iop.h"

#include "ps2_debug.h"
#include "ps2_exception.h"
#include "ps2_storage.h"

#include <delaythread.h>
#include <iopcontrol.h>
#include <kernel.h>
#include <loadfile.h>
#include <sbv_patches.h>
#include <sifrpc.h>

#include <stdio.h>
#include <string.h>

/* Generated by CMake from $PS2SDK/iop/irx. */
extern const unsigned char g_ps2_ioman_irx[];
extern const unsigned int g_ps2_ioman_irx_size;
extern const unsigned char g_ps2_iomanX_irx[];
extern const unsigned int g_ps2_iomanX_irx_size;
extern const unsigned char g_ps2_fileio_irx[];
extern const unsigned int g_ps2_fileio_irx_size;
extern const unsigned char g_ps2_sio2man_irx[];
extern const unsigned int g_ps2_sio2man_irx_size;
extern const unsigned char g_ps2_mcman_irx[];
extern const unsigned int g_ps2_mcman_irx_size;
extern const unsigned char g_ps2_mcserv_irx[];
extern const unsigned int g_ps2_mcserv_irx_size;
extern const unsigned char g_ps2_padman_irx[];
extern const unsigned int g_ps2_padman_irx_size;

static int s_did_reset;

int ps2_iop_did_reset(void)
{
    return s_did_reset;
}

static int iop_marker_present(const char* path)
{
    return ps2_storage_device_present(path);
}

static void iop_load_embedded(const char* name,
    const unsigned char* data,
    unsigned int size,
    const char* rom_fallback)
{
    int ret;

    ret = ps2_irx_exec(name, data, size);
    if (ret < 0 && rom_fallback != NULL) {
        ret = SifLoadModule(rom_fallback, 0, NULL);
        PS2_LOG("[ps2] iop: %s fallback %s -> %d", name, rom_fallback, ret);
    }

    if (ret < 0) {
        PS2_LOG("[ps2] iop: WARNING %s did not load", name);
    }
}

static void iop_load_rom_or_embedded(const char* name,
    const char* rom,
    const unsigned char* data,
    unsigned int size)
{
    int ret = SifLoadModule(rom, 0, NULL);

    if (ret >= 0) {
        PS2_LOG("[ps2] iop: %s loaded from %s (id %d)", name, rom, ret);
        return;
    }

    PS2_LOG("[ps2] iop: %s not in %s (ret %d), trying embedded", name, rom, ret);
    iop_load_embedded(name, data, size, NULL);
}

void ps2_iop_bringup(void)
{
    int i;
    int reset_ok = 0;
    int sync_ok = 0;

    if (ps2_storage_device_present("host:")) {
        PS2_LOG("[ps2] iop: host: available (PCSX2/ps2link), keeping loader I/O");
        return;
    }

    if (iop_marker_present("mass:/FALLOUT/NO_IOP_RESET")
        || iop_marker_present("mass:/NO_IOP_RESET")
        || iop_marker_present("mc0:/FALLOUT/NO_IOP_RESET")
        || iop_marker_present("mc0:/NO_IOP_RESET")) {
        PS2_LOG("[ps2] iop: NO_IOP_RESET marker present, keeping loader I/O");
        return;
    }

    printf("[ps2] iop: resetting the IOP for a clean hardware boot\n");
    PS2_LOG("[ps2] iop: resetting the IOP for a clean hardware boot");
    ps2_exception_step("iop-reset", 0);

    /* No RPC is in flight at this point: ps2_debug_init() moved after the
     * reset, so the only I/O so far is the loader's own launch. */
    sceSifInitRpc(0);

    for (i = 0; i < 50; i++) {
        if (SifIopReset("", 0)) {
            reset_ok = 1;
            break;
        }
        DelayThread(100000); /* 100 ms */
    }

    if (!reset_ok) {
        PS2_LOG("[ps2] iop: WARNING SifIopReset failed after 5 s, keeping loader I/O");
        sceSifInitRpc(0);
        return;
    }

    s_did_reset = 1;

    for (i = 0; i < 5000; i++) {
        if (SifIopSync()) {
            sync_ok = 1;
            break;
        }
        DelayThread(1000); /* 1 ms */
    }

    if (!sync_ok) {
        PS2_LOG("[ps2] iop: WARNING SifIopSync timed out after 5 s");
    }

    sceSifInitRpc(0);
    ps2_exception_step("iop-sync", (unsigned)sync_ok);

    /* LoadModuleBuffer needs the ROM LOADFILE patch; the prefix patch lets
     * embedded modules load from any device. Failures are logged but not
     * fatal: the ROM fallbacks below still have a chance. */
    {
        int lmb = sbv_patch_enable_lmb();
        int prefix = sbv_patch_disable_prefix_check();
        PS2_LOG("[ps2] iop: sbv lmb=%d prefix=%d", lmb, prefix);
    }

    /* Order matters: IOMAN -> IOMANX -> FILEIO, then SIO2MAN -> MCMAN ->
     * MCSERV. PADMAN is loaded again by ps2_input_init() on purpose. */
    iop_load_embedded("ioman.irx", g_ps2_ioman_irx, g_ps2_ioman_irx_size, "rom0:IOMAN");
    iop_load_embedded("iomanX.irx", g_ps2_iomanX_irx, g_ps2_iomanX_irx_size, "rom0:IOMANX");
    iop_load_embedded("fileio.irx", g_ps2_fileio_irx, g_ps2_fileio_irx_size, "rom0:FILEIO");
    ps2_exception_step("iop-fileio", 0);

    iop_load_rom_or_embedded("sio2man.irx", "rom0:SIO2MAN",
        g_ps2_sio2man_irx, g_ps2_sio2man_irx_size);
    iop_load_rom_or_embedded("mcman.irx", "rom0:MCMAN",
        g_ps2_mcman_irx, g_ps2_mcman_irx_size);
    iop_load_rom_or_embedded("mcserv.irx", "rom0:MCSERV",
        g_ps2_mcserv_irx, g_ps2_mcserv_irx_size);
    iop_load_rom_or_embedded("padman.irx", "rom0:PADMAN",
        g_ps2_padman_irx, g_ps2_padman_irx_size);

    ps2_exception_step("iop-base-done", 0);

    printf("[ps2] iop: base stack reloaded\n");
    PS2_LOG("[ps2] iop: base stack reloaded");
}
