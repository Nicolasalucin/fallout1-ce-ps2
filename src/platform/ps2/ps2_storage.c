void ps2_storage_init(const char* argv0)
{
    const char* ready = NULL;
    int tries = 0;
    int mc_tries;

    printf("[ps2] storage: ELF argv0 = '%s'\n", argv0 != NULL ? argv0 : "");
    PS2_LOG("[ps2] storage: ELF argv0 = '%s'", argv0 != NULL ? argv0 : "");

    storage_extract_elf_dir(argv0);
    if (s_elf_dir_ok) {
        printf("[ps2] storage: ELF directory = '%s'\n", s_elf_dir);
        PS2_LOG("[ps2] storage: ELF directory = '%s'", s_elf_dir);
    }

    /* Loader-managed I/O: ps2link provides host:, PCSX2 emulates host:.
     * Check this first so development/emulator boots never wait for USB. */
    if (storage_probe_dir("host:")) {
        printf("[ps2] storage: host: available (development I/O), skipping USB bring-up\n");
        PS2_LOG("[ps2] storage: host: available (development I/O), skipping USB bring-up");
        s_storage_initialized = 1;
        return;
    }

    /* A loader may have registered mass:/mass0: already, but that only means
     * the mount point exists: USB 1.1 still has to negotiate the stick and
     * read the MBR. Load the classic USB stack only when no mass device is
     * registered, then poll it below even in the loader-provided case. */
    if (!storage_probe_dir("mass:") && !storage_probe_dir("mass0:")) {
        printf("[ps2] storage: bringing up USB mass storage\n");
        PS2_LOG("[ps2] storage: bringing up USB mass storage");
        sceSifInitRpc(0);

        storage_exec_irx("usbd.irx", g_ps2_usbd_irx, g_ps2_usbd_irx_size);
        storage_exec_irx("usbhdfsd.irx", g_ps2_usbhdfsd_irx, g_ps2_usbhdfsd_irx_size);

        if (!storage_mass_present()) {
            /* BDM block-device layer (also the base for MX4SIO below). */
            storage_exec_irx("bdm.irx", g_ps2_bdm_irx, g_ps2_bdm_irx_size);
            storage_exec_irx("usbmass_bd.irx", g_ps2_usbmass_bd_irx, g_ps2_usbmass_bd_irx_size);
            storage_exec_irx("bdmfs_fatfs.irx", g_ps2_bdmfs_fatfs_irx, g_ps2_bdmfs_fatfs_irx_size);
        }

        if (!storage_mass_present()) {
            /* MX4SIO: SIO2-based memory card port adapter. */
            storage_exec_irx("sio2man.irx", g_ps2_sio2man_irx, g_ps2_sio2man_irx_size);
            storage_exec_irx("mx4sio_bd.irx", g_ps2_mx4sio_bd_irx, g_ps2_mx4sio_bd_irx_size);
        }
    } else {
        printf("[ps2] storage: mass: already registered by the loader, polling it anyway\n");
        PS2_LOG("[ps2] storage: mass: already registered by the loader, polling it anyway");
    }

    /* ================================================================
     * Active polling loop for mass: / mass0: / mass1: (USB 1.1).
     * usbd + usbhdfsd need 1.5-4 s on real hardware to negotiate the
     * stick, read the MBR and register the mount point. This loop runs
     * even when the loader already registered mass:, because the mount
     * point can exist before the bus finishes renegotiating.
     * ================================================================ */
    printf("[ps2] storage: waiting for mass: to settle (USB 1.1)...\n");
    PS2_LOG("[ps2] storage: waiting for mass: to settle (USB 1.1)...");
    tries = storage_wait_dir("mass:", 20, 300); /* 20 x 300 ms = 6.0 s */
    if (tries > 0) {
        ready = "mass:";
    } else {
        printf("[ps2] storage: mass: not ready, waiting for mass0:...\n");
        PS2_LOG("[ps2] storage: mass: not ready, waiting for mass0:...");
        tries = storage_wait_dir("mass0:", 10, 300); /* 10 x 300 ms = 3.0 s */
        if (tries > 0) {
            ready = "mass0:";
        }
    }

    if (ready == NULL) {
        printf("[ps2] storage: mass0: not ready, waiting for mass1:...\n");
        PS2_LOG("[ps2] storage: mass0: not ready, waiting for mass1:...");
        tries = storage_wait_dir("mass1:", 10, 300); /* 10 x 300 ms = 3.0 s */
        if (tries > 0) {
            ready = "mass1:";
        }
    }

    if (ready != NULL) {
        printf("[ps2] storage: %s ready after %d attempt(s)\n", ready, tries);
        PS2_LOG("[ps2] storage: %s ready after %d attempt(s)", ready, tries);
    } else {
        printf("[ps2] storage: WARNING mass:/mass0:/mass1: did not settle in time (timeout)\n");
        PS2_LOG("[ps2] storage: WARNING mass:/mass0:/mass1: did not settle in time (timeout)");
    }

    /* Memory card devices are brought up by ps2_iop_bringup(). A short
     * backoff here replaces the old fixed multi-second wait: by the time the
     * USB polling has finished, MCMAN/MCSERV have usually settled already. */
    mc_tries = storage_wait_dir("mc0:", 10, 100); /* 10 x 100 ms = 1.0 s max */
    if (mc_tries > 0) {
        printf("[ps2] storage: mc0: ready after %d attempt(s)\n", mc_tries);
        PS2_LOG("[ps2] storage: mc0: ready after %d attempt(s)", mc_tries);
    } else {
        printf("[ps2] storage: mc0: not available\n");
        PS2_LOG("[ps2] storage: mc0: not available");
    }

    if (ready != NULL) {
        printf("[ps2] storage: mass: ready (%s)\n", ready);
        PS2_LOG("[ps2] storage: mass: ready (%s)", ready);
    } else {
        printf("[ps2] storage: mass: not available\n");
        PS2_LOG("[ps2] storage: mass: not available (game data must be on mc0:/cdrom0:/hdd0:)");
    }

    s_storage_initialized = 1;
}
