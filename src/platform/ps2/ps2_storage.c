/* ------------------------------------------------------- argv0 parsing --- */

static const char* storage_last_sep(const char* s)
{
    const char* best = NULL;

    while (*s != '\0') {
        if (*s == '/' || *s == '\\') {
            best = s;
        }
        s++;
    }

    return best;
}

static void storage_extract_elf_dir(const char* argv0)
{
    const char* sep;
    const char* colon;
    const char* p;
    size_t len;
    int i;

    s_elf_dir_ok = 0;

    if (argv0 == NULL || argv0[0] == '\0') {
        return;
    }

    /* Some loaders hand the path over quoted. */
    if (argv0[0] == '"') {
        argv0++;
    }

    sep = storage_last_sep(argv0);
    colon = strchr(argv0, ':');

    if (sep != NULL) {
        if (colon == NULL) {
            /* Deviceless relative path: nothing we can probe directly. */
            return;
        }
        len = (size_t)(sep - argv0) + 1; /* keep the trailing separator */
    } else if (colon != NULL) {
        len = (size_t)(colon - argv0) + 1; /* device root, e.g. "mass:" */
    } else {
        /* Bare file name: not usable for probing. */
        return;
    }

    if (len == 0 || len + 2 > sizeof(s_elf_dir)) {
        return;
    }

    memcpy(s_elf_dir, argv0, len);
    for (i = 0; i < (int)len; i++) {
        if (s_elf_dir[i] == '\\') {
            s_elf_dir[i] = '/';
        }
    }
    if (s_elf_dir[len - 1] != '/') {
        s_elf_dir[len++] = '/';
    }
    s_elf_dir[len] = '\0';
    s_elf_dir_ok = 1;
}

const char* ps2_storage_elf_dir(void)
{
    return s_elf_dir_ok ? s_elf_dir : NULL;
}

/* --------------------------------------------------------- IOP modules --- */

/* Device/directory existence probe. stat() is the cheap path and works for
 * files and directories on FAT32, PFS, ISO9660 and PCSX2 hostfs. Some IOP
 * drivers only answer a directory open for a device root, so retry both
 * spellings with open() before declaring the device absent.
 *
 * opendir() is deliberately avoided: a failed opendir() on a missing device
 * can leave the PCSX2 hostfs HLE in a corrupt state, and the plain directory
 * open is enough to ask fileio whether a mount point exists. (This ps2sdk's
 * newlib port does not expose dopen()/dclose(); open()/close() are the
 * supported equivalent here.) */
static int storage_probe_dir(const char* dev)
{
    char with_slash[PS2_STORAGE_DIR_MAX + 2];
    struct stat st;
    int fd;

    with_slash[0] = '\0';

    if (dev == NULL || dev[0] == '\0') {
        return 0;
    }

    if (stat(dev, &st) == 0) {
        return 1;
    }

    if (snprintf(with_slash, sizeof(with_slash), "%s/", dev) < (int)sizeof(with_slash)
        && stat(with_slash, &st) == 0) {
        return 1;
    }

    fd = open(dev, O_RDONLY);
    if (fd >= 0) {
        close(fd);
        return 1;
    }

    if (with_slash[0] != '\0') {
        fd = open(with_slash, O_RDONLY);
        if (fd >= 0) {
            close(fd);
            return 1;
        }
    }

    return 0;
}

/* Active wait for a device root. Returns the 1-based attempt number on
 * success, or 0 on timeout. Each failed attempt sleeps `step_ms` before the
 * next probe. */
static int storage_wait_dir(const char* dev, int attempts, unsigned int step_ms)
{
    int i;

    for (i = 0; i < attempts; i++) {
        if (storage_probe_dir(dev)) {
            return i + 1;
        }

        ps2_exception_step("storage-poll", (unsigned)i);
        DelayThread(step_ms * 1000);
    }

    return 0;
}

int ps2_storage_device_present(const char* path)
{
    return storage_probe_dir(path);
}

/* A mass device already registered by the loader is not necessarily ready:
 * USB 1.1 still has to negotiate the stick and read the MBR. This helper is
 * only used to decide whether the USB modules need loading, never as an
 * early-return condition for the polling loop. */
static int storage_mass_present(void)
{
    return storage_probe_dir("mass:")
        || storage_probe_dir("mass0:");
}

void ps2_storage_get_status(ps2_storage_status_t* out)
{
    if (out == NULL) {
        return;
    }

    out->mass = ps2_storage_device_present("mass:");
    out->mass0 = ps2_storage_device_present("mass0:");
    out->mass1 = ps2_storage_device_present("mass1:");
    out->mc0 = ps2_storage_device_present("mc0:");
    out->host = ps2_storage_device_present("host:");
}

static int storage_exec_irx(const char* name, const unsigned char* data, unsigned int size)
{
    int ret = ps2_irx_exec(name, data, size);

    /* The usual failure is "already loaded" (OPL/uLaunchELF preload their
     * IOP stack); a missing dependency or dead device lands here too. Both
     * are non-fatal: the device probe below is the real test. */
    return ret >= 0 ? 0 : -1;
}

int ps2_irx_exec(const char* name, const unsigned char* data, unsigned int size)
{
    int result = 0;
    const unsigned char* src = data;
    unsigned int mod16 = (unsigned int)((uintptr_t)data & 0xF);
    int ret;

    if (mod16 != 0) {
        if (size > sizeof(s_irx_bounce)) {
            printf("[ps2] storage: %s too large for IRX bounce buffer (%u bytes)\n", name, size);
            PS2_LOG("[ps2] irx: %s FAILED (size %u > bounce %u)", name, size, (unsigned int)sizeof(s_irx_bounce));
            return -1;
        }

        memcpy(s_irx_bounce, data, size);
        src = s_irx_bounce;
        printf("[ps2] storage: %s at %p (mod16=%u), using aligned bounce buffer\n",
            name, (const void*)data, mod16);
    }

    ret = SifExecModuleBuffer((void*)src, size, 0, NULL, &result);

    if (ret >= 0) {
        printf("[ps2] storage: %s loaded (id %d, result %d, mod16=%u)\n", name, ret, result, mod16);
        PS2_LOG("[ps2] irx: %s loaded (id %d, result %d, src_mod16=%u)", name, ret, result, mod16);
        return ret;
    }

    printf("[ps2] storage: %s not loaded (ret %d, result %d, mod16=%u) - continuing\n",
        name, ret, result, mod16);
    PS2_LOG("[ps2] irx: %s not loaded (ret %d, result %d, src_mod16=%u)", name, ret, result, mod16);
    return ret;
}

static void storage_report_irx(const char* name, const unsigned char* data, unsigned int size)
{
    unsigned int mod16 = (unsigned int)((uintptr_t)data & 0xF);

    printf("[ps2] irx: %-16s addr=%p size=%u mod16=%u%s\n",
        name, (const void*)data, size, mod16, mod16 == 0 ? "" : " (NEEDS BOUNCE)");
    PS2_LOG("[ps2] irx: %-16s addr=0x%08x size=%u mod16=%u%s",
        name, (unsigned int)(uintptr_t)data, size, mod16, mod16 == 0 ? "" : " (NEEDS BOUNCE)");
}

