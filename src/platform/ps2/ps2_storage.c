/*
 * PS2 storage bootstrap (F9) - see ps2_storage.h for the design notes.
 *
 * Module bring-up is tiered so the risky stacks are only touched when the
 * cheap ones did not produce a "mass:" device:
 *
 *   tier 1  usbd + usbhdfsd                          USB stick (classic)
 *   tier 2  bdm + usbmass_bd + bdmfs_fatfs           BDM USB (OPL-style)
 *   tier 3  sio2man + mx4sio_bd + (bdm stack)        MX4SIO
 *
 * Every load result is logged; failures (including "already loaded") never
 * stop the boot because the game may well be reading from mc0/host/cdrom
 * instead.
 */

